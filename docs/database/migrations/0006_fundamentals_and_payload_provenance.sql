CREATE TABLE m2_provider_fetches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    fetch_key BINARY(32) NOT NULL,
    source_id BIGINT UNSIGNED NOT NULL,
    asset_id BIGINT UNSIGNED NULL,
    route_id BIGINT UNSIGNED NULL,
    route_revision INT UNSIGNED NULL,
    route_sha256 BINARY(32) NULL,
    job_run_id BIGINT UNSIGNED NULL,
    file_id BIGINT UNSIGNED NOT NULL,
    payload_sha256 BINARY(32) NOT NULL,
    payload_bytes BIGINT UNSIGNED NOT NULL,
    content_type VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
    observed_at DATETIME(6) NOT NULL,
    http_status SMALLINT UNSIGNED NULL,
    parser_key VARCHAR(64) COLLATE utf8mb4_0900_bin NULL,
    parser_version VARCHAR(64) COLLATE utf8mb4_0900_bin NULL,
    parse_status VARCHAR(16) COLLATE utf8mb4_0900_bin NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_fetch_key (fetch_key),
    UNIQUE KEY uq_fetch_source (id, source_id),
    KEY ix_fetch_source_time (source_id, observed_at, id),
    KEY ix_fetch_asset_time (asset_id, observed_at, id),
    KEY ix_fetch_route (route_id),
    KEY ix_fetch_job (job_run_id),
    KEY ix_fetch_file (file_id),
    KEY ix_fetch_payload (payload_sha256, payload_bytes, id),
    CONSTRAINT fk_fetch_source FOREIGN KEY (source_id) REFERENCES m2_sources (id) ON DELETE RESTRICT,
    CONSTRAINT fk_fetch_asset FOREIGN KEY (asset_id) REFERENCES m2_assets (entity_id) ON DELETE RESTRICT,
    CONSTRAINT fk_fetch_route FOREIGN KEY (route_id) REFERENCES m2_asset_source_routes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_fetch_job FOREIGN KEY (job_run_id) REFERENCES m2_job_runs (id) ON DELETE RESTRICT,
    CONSTRAINT fk_fetch_file FOREIGN KEY (file_id) REFERENCES m2_files (id) ON DELETE RESTRICT,
    CONSTRAINT ck_fetch_route CHECK (((route_id IS NULL AND route_revision IS NULL AND route_sha256 IS NULL) OR (route_id IS NOT NULL AND asset_id IS NOT NULL AND route_revision IS NOT NULL AND route_revision > 0 AND route_sha256 IS NOT NULL)) IS TRUE),
    CONSTRAINT ck_fetch_parser CHECK (((parse_status = 'unparsed' AND parser_key IS NULL AND parser_version IS NULL) OR ((parse_status = 'parsed' OR parse_status = 'partial' OR parse_status = 'rejected' OR parse_status = 'failed') AND parser_key IS NOT NULL AND parser_key <> '' AND parser_version IS NOT NULL AND parser_version <> '')) IS TRUE),
    CONSTRAINT ck_fetch_metadata CHECK ((content_type <> '' AND (http_status IS NULL OR (http_status >= 100 AND http_status <= 599)) AND created_at >= observed_at) IS TRUE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE m2_fundamental_metrics (
    metric_key VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    category VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
    value_type VARCHAR(16) COLLATE utf8mb4_0900_bin NOT NULL,
    value_semantics VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
    dimension_key VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
    definition_sha256 BINARY(32) NOT NULL,
    status VARCHAR(16) COLLATE utf8mb4_0900_bin NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (metric_key),
    UNIQUE KEY uq_metric_contract (metric_key, value_type, dimension_key),
    CONSTRAINT ck_metric_definition CHECK ((metric_key <> '' AND display_name <> '' AND category <> '' AND value_semantics <> '' AND dimension_key <> '' AND ((value_type = 'decimal' AND dimension_key <> 'text' AND dimension_key <> 'date') OR (value_type = 'text' AND dimension_key = 'text') OR (value_type = 'date' AND dimension_key = 'date')) AND (status = 'active' OR status = 'retired') AND updated_at >= created_at) IS TRUE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

