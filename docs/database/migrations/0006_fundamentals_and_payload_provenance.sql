    CONSTRAINT ck_fund_unit_currency CHECK ((((dimension_key = 'monetary' OR dimension_key = 'monetary_per_share') AND monetary_currency_code IS NOT NULL) OR ((dimension_key <> 'monetary' AND dimension_key <> 'monetary_per_share') AND monetary_currency_code IS NULL)) IS TRUE)
