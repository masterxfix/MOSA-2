"""Render the three complete M2 entry pages from the shared shell and Main fragments."""
import argparse
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    "index.html": ("overview", "Projektüberblick", "Finanzdaten mit Kontext",
                   "MOSA 2: persönliche, finanzorientierte Daten- und KI-Plattform. Projektziel, geprüfte Ergebnisse und nächste Entwicklungsschritte."),
    "marktdaten.html": ("market", "Marktdaten & Messungen", "Gespeicherte Marktdaten",
                        "MOSA 2: persönliche, finanzorientierte Daten- und KI-Plattform. Gespeicherte Marktdaten, Datenstatus und Messungen der Testumgebung."),
    "fundamentaldaten.html": ("fundamentals", "Fundamentaldaten", "Gespeicherte Fundamentaldaten",
                              "MOSA 2: gespeicherte Fundamentaldaten mit Jahresvergleich, Quellen und nachvollziehbaren Referenzen."),
}


def render(filename):
    key, title, label, description = PAGES[filename]
    fragment = (ROOT / f"assets/main-{key}.html").read_text(encoding="utf-8").rstrip()
    links = []
    for file, (_, name, _, _) in PAGES.items():
        href = "./" if file == "index.html" else file
        current = ' aria-current="page"' if file == filename else ''
        links.append(f'      <a href="{href}"{current}>{escape(name)}</a>')
    nav = "\n".join(links)
    brand = "#inhalt" if key == "overview" else "./"
    stored = " data-isin-stored-quotes" if key != "fundamentals" else ""
    latency = (' inkl. Daten · <span data-fundamentals-load-time>— ms</span>' if key == "fundamentals"
               else ' · <span data-page-load-time aria-label="Seitenladezeit wird gemessen">— ms</span>')
    scripts = ['codex_status.js?v=20261110']
    if key == "fundamentals":
        scripts.append('fundamentals.js?v=20261110-empty')
    else:
        scripts.insert(0, 'page_load_time.js')
        if key == "market":
            scripts.append('market.js')
        scripts.append('isin_quotes.js?v=isin-20261110-market-focus')
    scripts = "\n".join(f'  <script src="assets/js/{src}" defer></script>' for src in scripts)
    return f'''<!doctype html>
<!-- Generated by scripts/build_pages.py. Edit the shared shell there and Main in assets/main-*.html. -->
<html lang="de">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{escape(description)}">
  <meta name="color-scheme" content="dark">
  <title>MOSA 2 · {escape(title)}</title>
  <link rel="stylesheet" href="assets/css/main.css?v=nova-symbol-20261110">
{scripts}
</head>
<body{stored} class="{key}-page">
  <a class="skip-link" href="#inhalt">Zum Inhalt</a>
  <header>
    <div class="topbar wrap">
      <a class="brand" href="{brand}" aria-label="MOSA 2 – Projektüberblick"><span class="brand-symbol" aria-hidden="true">m</span>MOSA <span class="brand-version">2</span></a>
      <span class="project-label">{label} <span class="dot" aria-hidden="true"></span> Testumgebung</span>
      <span class="ai-symbols">
        <span class="codex-status-symbol" data-codex-status data-state="unavailable" role="img" aria-label="Codex-Status unbekannt" title="Codex-Status unbekannt"></span>
        <span class="nova-symbol" role="img" aria-label="NOVA" title="NOVA"></span>
      </span>
    </div>
    <nav class="site-nav wrap" aria-label="Seitennavigation" data-site-nav>
{nav}
    </nav>
  </header>
{fragment}
  <footer class="wrap footer">
    <span>MOSA 2 · Auf verlässlichen Grundlagen aufgebaut.</span>
    <span class="footer-latency">Seitenladezeit{latency}</span>
    <span class="footer-release">Entwicklung · Keine Produktivfreigabe</span>
  </footer>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated pages without writing")
    args = parser.parse_args()
    for filename in PAGES:
        path = ROOT / filename
        expected = render(filename)
        if args.check:
            if path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{filename} is stale; run python scripts/build_pages.py\n")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
